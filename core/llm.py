# DeepSeek API
DEEPSEEK_API_URL = "https://api.deepseek.com/v1/chat/completions"
DEEPSEEK_MODEL = "deepseek-chat"  # V3 输出 8K token,长报告不卡 (8-2 15:39 改回)


def call_deepseek(system_prompt: str, user_prompt: str, timeout: int = 60) -> dict:
    """
    调用 DeepSeek,返回 {content, usage}
    usage = {prompt_tokens, completion_tokens, total_tokens}
    失败抛 RuntimeError
    """
    api_key = os.environ.get("DEEPSEEK_API_KEY", "")
    if not api_key:
        raise RuntimeError("DEEPSEEK_API_KEY 未配置")
    if not api_key.startswith("sk-") or len(api_key) < 30:
        raise RuntimeError("DEEPSEEK_API_KEY 格式无效")

    payload = {
        "model": DEEPSEEK_MODEL,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
        "temperature": 0.7,
        "max_tokens": 8000,  # 上限 8 千字,够日复盘 1-2k / 周复盘 2-4k / 重大不限
    }

    req = urllib.request.Request(
        DEEPSEEK_API_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
    )

    with urllib.request.urlopen(req, timeout=timeout) as resp:
        result = json.loads(resp.read().decode("utf-8"))

    content = result["choices"][0]["message"]["content"]
    usage = result.get("usage", {})

    return {"content": content, "usage": usage}


